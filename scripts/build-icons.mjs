/* ============================================================
   Generates src/components/ui/icon-paths.ts from Google's Material
   Symbols SVGs (@material-symbols/svg-400 and -600, rounded).

   Run: npm run icons

   Why generate instead of loading the icon font: only the icons
   listed below end up in the bundle, there is no network request and
   no FOUT, and the glyphs stay inline SVG — which is what the rest of
   the stylesheet is written against.

   This map is the single source of truth for the site's icon
   vocabulary. Add a row, run the script, and the name is available as
   <Icon name="..." /> with the type updated to match.

     fill: true   also pull the filled cut (for `filled` call sites)
     bold: true   also pull weight 600 (for `strokeWidth` >= 2.2)
   ============================================================ */

