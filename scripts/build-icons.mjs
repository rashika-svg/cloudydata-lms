/* Every glyph in the packages is a single <path d> on a 0 -960 960 960
   grid, so pulling the one attribute is enough. */
function pathOf(weight, file) {
  const svg = readFileSync(join(ROOT, 'node_modules', `@material-symbols/svg-${weight}`, 'rounded', `${file}.svg`), 'utf8')
  const d = svg.match(/ d="([^"]+)"/)
  if (!d) throw new Error(`no path in ${file}.svg (weight ${weight})`)
  return d[1]
}

const rows = Object.entries(ICONS).map(([key, spec]) => {
  const { name, fill, bold } = typeof spec === 'string' ? { name: spec } : spec
  const cuts = [`d: '${pathOf(400, name)}'`]
  if (fill) cuts.push(`f: '${pathOf(400, `${name}-fill`)}'`)
  if (bold) cuts.push(`b: '${pathOf(600, name)}'`)
  const prop = /^[a-z][a-z0-9]*$/i.test(key) ? key : `'${key}'`
  return `  ${prop}: {\n    /* ${name} */\n    ${cuts.join(',\n    ')},\n  },`
})

const out = `/* ============================================================
   GENERATED by scripts/build-icons.mjs — do not edit by hand.

   Google Material Symbols (Rounded), drawn on a 0 -960 960 960 grid.
   d = weight 400 · f = filled cut · b = weight 600

   To add or change an icon, edit the map in the script and run
   \`npm run icons\`.
   ============================================================ */

export interface IconCuts {
  /** weight 400 */
  d: string
  /** filled */
  f?: string
  /** weight 600 */
  b?: string
}

export const ICON_PATHS = {
${rows.join('\n')}
} satisfies Record<string, IconCuts>
`

writeFileSync(join(ROOT, 'src/components/ui/icon-paths.ts'), out)
